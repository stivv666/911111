using System;

// Класс StaticWordProvider реализует интерфейс IWordProvider.
// Это означает, что он ОБЯЗАН содержать методы GetWord() и GetHint(), 
// иначе программа просто не скомпилируется.
public class StaticWordProvider : IWordProvider
{
    // Создаем массив строк для хранения самих слов. 
    // Выделяем память с запасом — на 100 слов.
    private string[] words = new string[100];

    // Создаем параллельный массив для хранения подсказок.
    // Индекс слова в массиве 'words' будет строго совпадать с индексом его подсказки в 'hints'.
    private string[] hints = new string[100];

    // Переменная для хранения реального количества добавленных слов (чтобы не выбирать пустые ячейки).
    private int _wordCount = 0;
    
    // Переменная, которая запоминает индекс текущего выбранного слова.
    // Это нужно, чтобы метод GetHint() знал, какую именно подсказку возвращать.
    private int _currentIndex = 0;
    
    // Создаем объект класса Random для генерации случайных чисел.
    private Random _random = new Random();

    // Конструктор класса. Вызывается один раз при создании объекта (в GameController).
    public StaticWordProvider()
    {
        // Заполняем массивы хардкодными (вписанными вручную) значениями.
        // Каждому слову соответствует подсказка под тем же индексом.
        words[0] = "алгоритм"; hints[0] = "Набір інструкцій для вирішення задачі";
        words[1] = "інтерфейс"; hints[1] = "Спільна межа між двома системами або класами";
        words[2] = "процесор"; hints[2] = "Головний мозок комп'ютера";
        words[3] = "компілятор"; hints[3] = "Перекладає код у машинну мову";
        words[4] = "програміст"; hints[4] = "Людина, яка перетворює каву на код";
        words[5] = "спадкування"; hints[5] = "Принцип ООП (передача властивостей від батьківського класу)";

        // Указываем, что мы заполнили ровно 6 ячеек (от 0 до 5).
        _wordCount = 6;
    }

    // Метод, который требует интерфейс IWordProvider. Вызывается перед началом раунда.
    public string GetWord()
    {
        // Генерируем случайное число от 0 (включительно) до _wordCount (не включительно, то есть до 5).
        // Сохраняем это число в _currentIndex, чтобы запомнить выбор.
        _currentIndex = _random.Next(0, _wordCount);
        
        // Возвращаем случайное слово из массива.
        return words[_currentIndex];
    }

    // Еще один обязательный метод из интерфейса.
    public string GetHint()
    {
        // Поскольку метод GetWord() уже выбрал случайный индекс и сохранил его в _currentIndex,
        // мы просто возвращаем подсказку под тем же самым индексом.
        return hints[_currentIndex];
    }
}