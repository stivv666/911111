using System;

// Базовый абстрактный класс для любой словесной игры.
// Ключевое слово 'abstract' означает, что мы не можем создать объект этого класса напрямую 
// (нельзя написать: var game = new WordGameBase()). 
// Этот класс служит исключительно как "фундамент" или чертеж для других игр.
public abstract class WordGameBase
{
    // Свойство для хранения количества оставшихся жизней (попыток).
    // get; — разрешает ПУБЛИЧНОЕ чтение. Любой внешний класс (например, GameController) 
    // может узнать, сколько жизней осталось, чтобы вывести их на экран.
    // protected set; — разрешает ЗАЩИЩЕННУЮ запись. Изменять это значение может только 
    // этот класс и его классы-наследники (в нашем случае HangmanGame отнимает жизнь при ошибке).
    public int AttemptsLeft { get; protected set; }

    // Абстрактный метод для попытки угадать букву.
    // Обратите внимание: здесь нет фигурных скобок {} с кодом. 
    // Это строгое правило для наследников: "Если ты хочешь быть словесной игрой, 
    // ты ОБЯЗАН реализовать логику проверки буквы (через ключевое слово override)".
    public abstract bool MakeGuess(char letter);

    // Еще один абстрактный метод для проверки, завершена ли игра.
    // Опять же, без реализации здесь. Каждая конкретная игра (виселица, поле чудес, балда) 
    // сама определяет свои условия окончания, поэтому логика пишется в классе-наследнике.
    public abstract bool IsGameOver();
}