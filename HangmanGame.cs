using System;

// Класс HangmanGame наследуется от базового класса WordGameBase.
// Это значит, что он получает все свойства и методы родителя (например, свойство AttemptsLeft).
public class HangmanGame : WordGameBase
{
    // Приватная переменная для хранения загаданного слова.
    // Она скрыта от других классов, чтобы никто не мог "подсмотреть" или изменить слово во время игры.
    private string _targetWord;

    // Массив символов, который хранит текущий прогресс отгадывания.
    // Выделено ровно 20 ячеек (максимальная длина слова в нашей игре — 20 букв).
    private char[] progress = new char[20];
    
    // Переменная для хранения фактической длины загаданного слова.
    private int _targetLength;

    // Конструктор: вызывается при создании новой игры в GameController.
    public HangmanGame(string word, int maxAttempts)
    {
        // Переводим слово в нижний регистр, чтобы игра не зависела от того,
        // большими или маленькими буквами оно было написано в словаре.
        _targetWord = word.ToLower();
        
        // Устанавливаем количество жизней (свойство, унаследованное от WordGameBase).
        AttemptsLeft = maxAttempts;
        
        // Запоминаем длину слова.
        _targetLength = _targetWord.Length;

        // Цикл для начальной настройки массива прогресса.
        for (int i = 0; i < 20; i++)
        {
            // Если индекс меньше длины слова, ставим символ подчеркивания '_',
            // который означает неотгаданную букву.
            if (i < _targetLength)
                progress[i] = '_';
            // Остальные ячейки (до 20) заполняем пустым символом (нуль-терминатором),
            // так как они нам не нужны для этого слова.
            else
                progress[i] = '\0';
        }
    }

    // Метод для обработки попытки угадать букву. 
    // Ключевое слово override означает, что мы переопределяем метод из базового класса WordGameBase.
    public override bool MakeGuess(char letter)
    {
        // Переводим введенную букву в нижний регистр для корректного сравнения.
        letter = char.ToLower(letter);
        
        // Флаг, который покажет, угадали ли мы хотя бы одну букву.
        bool hit = false;

        // Проходимся по каждой букве загаданного слова.
        for (int i = 0; i < _targetLength; i++)
        {
            // Если буква в слове совпадает с введенной И она еще не была открыта (там стоит '_')
            if (_targetWord[i] == letter && progress[i] == '_')
            {
                // Заменяем подчеркивание на саму букву в массиве прогресса.
                progress[i] = letter;
                // Отмечаем, что было попадание.
                hit = true;
            }
        }

        // Если совпадений не было (hit остался false)
        if (!hit)
        {
            // Отнимаем одну жизнь.
            AttemptsLeft--;
        }

        // Возвращаем результат (true - угадал, false - ошибся).
        return hit;
    }

    // Метод для получения строки текущего прогресса (например, "_ a _ _").
    public string GetProgressString()
    {
        string result = "";
        // Собираем буквы и подчеркивания из массива progress в одну строчку.
        for (int i = 0; i < _targetLength; i++)
        {
            result += progress[i];
        }
        return result;
    }

    // Метод проверки на победу.
    public bool IsWon()
    {
        // Проверяем все буквы в слове.
        for (int i = 0; i < _targetLength; i++)
        {
            // Если находим хотя бы одно подчеркивание '_', значит слово еще не отгадано до конца.
            if (progress[i] == '_') return false;
        }
        // Если цикл завершился и подчеркиваний нет — игрок победил!
        return true;
    }

    // Метод проверки на окончание игры (переопределяет базовый метод).
    public override bool IsGameOver()
    {
        // Игра окончена, если жизней не осталось (<= 0) ИЛИ если игрок уже выиграл.
        return AttemptsLeft <= 0 || IsWon();
    }

    // Короткий метод (Expression-bodied member) для получения загаданного слова.
    // Используется контроллером, чтобы показать слово, если игрок проиграл.
    public string GetSecretWord() => _targetWord;
}